public class GabungString {
    public static void main(String[] args) {
        // Deklarasi dan instansiasi dua object String terpisah
        String depan = "Java";
        String belakang = "Fundamentals";

        // Menggabungkan keduanya menggunakan operator '+' dan menetapkannya ke object ketiga
        String hasil = depan + " " + belakang;

        // Output hasil
        System.out.println("Hasil penggabungan: " + hasil);
    }
}